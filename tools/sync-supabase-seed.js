#!/usr/bin/env node
/* Rebuilds the seed section of supabase_schema.sql from data.js so the
   database script always matches the site. Run:  node tools/sync-supabase-seed.js */
const fs = require("fs"), vm = require("vm"), path = require("path");
const root = path.join(__dirname, "..");
const ctx = {}; vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(root, "data.js"), "utf8").replace(/^const /gm, "var "), ctx);
const q = (v) => v == null || v === "" ? "NULL" : "'" + String(v).replace(/'/g, "''") + "'";
const arr = (a) => "ARRAY[" + a.map((x) => q(x)).join(", ") + "]::text[]";
const cols = "id, name, city, city_emoji, country, genre, genre_emoji, era, movies, scene, story, booking_url, photo, photo_credit, photo_gradient";
const inserts = ctx.HOTELS.map((h) =>
  `INSERT INTO hotels (${cols})\nVALUES (${[q(h.id), q(h.name), q(h.city), q(h.cityEmoji), q(h.country), q(h.genre), q(h.genreEmoji), q(h.era), arr(h.movies), q(h.scene), q(h.story), q(h.bookingUrl), q(h.photo), q(h.photoCredit), q(h.photoGradient)].join(", ")})\nON CONFLICT (id) DO UPDATE SET story = EXCLUDED.story;\n`
).join("\n");
const file = path.join(root, "supabase_schema.sql");
let sql = fs.readFileSync(file, "utf8");
const START = "-- >>> SEED START", END = "-- <<< SEED END";
const block = `${START} (auto-generated by tools/sync-supabase-seed.js — ${ctx.HOTELS.length} hotels)\n${inserts}\n${END}\n`;
if (sql.includes(START)) sql = sql.replace(new RegExp(START + "[\\s\\S]*?" + END + "\\n?"), block);
else sql = sql.slice(0, sql.indexOf("-- Seed data")) + "-- Seed data below is kept in sync with data.js.\n-- Safe to re-run — existing rows are kept (only 'story' is refreshed).\n\n" + block;
fs.writeFileSync(file, sql);
console.log("Seed synced:", ctx.HOTELS.length, "hotels");
